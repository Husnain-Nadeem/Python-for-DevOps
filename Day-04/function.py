def add(a,b):
    c= a + b
    return c
def subtract(a,b):
    c= a - b
    return c
def multiply(a,b):
    c= a * b
    return c
def divide(a,b):
    c= a / b
    return c

print ("Addition is:", add(10,20))
print ("Subtraction is:", subtract(20,10))
print ("Multiplication is:", multiply(10,20))
print ("Division is:", divide(20,10))
