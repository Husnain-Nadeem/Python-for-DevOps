## Task 2: Comparison Operators

print("Comparison Operators in Python")
print("Enter a number: ")
a = float(input())
print("Enter another number: ")
b = float(input())

print(f"{a} > {b}: {a > b}")
print(f"{a} < {b}: {a < b}")
print(f"{a} == {b}: {a == b}")
print(f"{a} != {b}: {a != b}")
print(f"{a} >= {b}: {a >= b}")
print(f"{a} <= {b}: {a <= b}")